def test_normalise_rules(text: str, source: str, expected: tuple[str, str | None, str | None, bool]) -> None:
    kind, cleaned, platform, attachment = normalise(text, source)
    assert (kind, platform, attachment) == (expected[0], expected[2], expected[3])
    if expected[1] is not None:
        assert cleaned == expected[1]


