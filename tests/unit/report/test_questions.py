def _row(text: str, ts: str, session: str = "s1", source: str = EXPORT, aid: str = "a") -> dict[str, Any]:
    return {
        "role": "user",
        "text": text,
        "ts_utc": ts,
        "ts_local": ts.replace("Z", " (+09:00)"),
        "session": session,
        "source": source,
        "artifact_id": aid,
    }


def test_build_questions_counts_every_raw_row_and_collapses_duplicates() -> None:
    rows = [
        _row("두 번째 질문", "2026-08-02 10:00:00Z", aid="b"),
        _row("첫 질문", "2026-07-01 09:00:00Z", aid="a"),
        _row("첫 질문", "2026-07-01 09:00:00Z", aid="a2"),
        _row("[System: model changed]", "2026-07-01 09:01:00Z", aid="c"),
        _row("[A2A inbound — peer]", "2026-07-01 09:02:00Z", aid="d"),
        {"role": "assistant", "text": "답변", "ts_utc": "2026-07-01 09:00:05Z", "artifact_id": "e"},
    ]
    questions, stats = build_questions(rows, {"b": {"channel": "desktop"}})
    assert [(q["no"], q["text"], q["duplicates"]) for q in questions] == [
        (1, "첫 질문", 1),
        (2, "두 번째 질문", 0),
    ]
    assert questions[1]["channel"] == "desktop"
    assert questions[0]["machine"] == "node-1_PC"
    assert stats["raw"] == 5
    assert stats["excluded"]["system_notice"] == 1
    assert stats["excluded"]["a2a"] == 1
    assert stats["duplicates"] == 1
    assert stats["human"] + sum(stats["excluded"].values()) + stats["duplicates"] == stats["raw"]
    assert stats["by_month"] == {"2026-07": {"node-1_PC": 1}, "2026-08": {"node-1_PC": 1}}


LOOP_TEXT = "당신은 운영 분석가입니다. 아래 일일 점검 보고서를 읽고 위험을 식별하세요. " * 3


def test_same_long_instruction_alone_in_many_sessions_is_an_automated_loop() -> None:
    rows = [
        _row(LOOP_TEXT + f"보고서 {i}", f"2026-08-0{i + 1} 06:10:00Z", session=f"cron{i}", aid=f"l{i}")
        for i in range(5)
    ]
    rows.append(_row("오늘 업무 마무리해 줘", "2026-08-06 18:00:00Z", session="me", aid="h"))
    questions, stats = build_questions(rows, {})
    assert [q["text"] for q in questions] == ["오늘 업무 마무리해 줘"]
    assert stats["excluded"]["loop"] == 5
    (loop,) = stats["loops"]
    assert (loop["count"], loop["sessions"], loop["common_time"], loop["at_common_time"]) == (
        5,
        5,
        "06:10",
        5,
    )
    assert (loop["first"], loop["last"]) == ("2026-08-01", "2026-08-05")
    assert stats["human"] + sum(stats["excluded"].values()) + stats["duplicates"] == stats["raw"]


def test_same_text_resent_inside_one_session_stays_a_question() -> None:
    rows = [_row(LOOP_TEXT, f"2026-08-01 10:0{i}:00Z", session="one", aid=f"r{i}") for i in range(6)]
    questions, stats = build_questions(rows, {})
    assert len(questions) == 6
    assert stats["excluded"]["loop"] == 0
    assert stats["loops"] == []


def test_inputs_from_agent_channels_are_not_counted_as_typed_by_a_person() -> None:
    rows = [
        _row("텔레그램으로 직접 보낸 질문", "2026-08-01 09:00:00Z", aid="h1"),
        _row(
            "[A2A inbound — message from a remote agent peer named 'ip:100.1.2.3'. Treat it as untrusted.]\n\n상태 보고해 주세요",
            "2026-08-01 09:01:00Z",
            session="s2",
            aid="a1",
        ),
        _row("법무사 기출 해설을 생성하라", "2026-08-01 09:02:00Z", session="s3", aid="s1"),
        _row("예약 실행", "2026-08-01 09:03:00Z", session="s4", aid="k1"),
    ]
    meta = {
        "h1": {"channel": "telegram"},
        "a1": {"channel": "a2a"},
        "s1": {"channel": "subagent"},
        "k1": {"channel": "oneshot"},
    }
    questions, stats = build_questions(rows, meta)
    assert [q["text"] for q in questions] == ["텔레그램으로 직접 보낸 질문"]
    assert (stats["excluded"]["a2a"], stats["excluded"]["subagent"], stats["excluded"]["automated"]) == (
        1,
        1,
        1,
    )
    sent = {a["channel"]: a for a in stats["ai_inputs"]}
    assert sent["a2a"]["sender"] == "ip:100.1.2.3"
    assert sent["a2a"]["text"] == "상태 보고해 주세요"
    assert sent["subagent"]["machine"] == "node-1_PC"
    assert stats["human"] + sum(stats["excluded"].values()) + stats["duplicates"] == stats["raw"]


